import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { basename, resolve } from "node:path";

const root = process.cwd();
const source = resolve(root, "brand/split-k/lockups");
const output = resolve(root, "public/branding");
const rules = JSON.parse(await readFile(resolve(root, "brand/split-k/wordmark-source/lockup-rules.json"), "utf8"));
const files = [["horizontal.svg", "brand-lockup.svg"], ["horizontal-reversed.svg", "brand-lockup-dark.svg"]];

await mkdir(output, { recursive: true });
for (const [canonical, destination] of files) {
  const bytes = await readFile(resolve(source, canonical));
  const sha256 = createHash("sha256").update(bytes).digest("hex");
  if (sha256 !== rules.approvedHorizontalSha256[canonical]) throw new Error(`Canonical brand asset changed: ${canonical}`);
  await writeFile(resolve(output, destination), bytes);
}
const manifest = JSON.parse(await readFile(resolve(root, "brand/split-k/web/asset-manifest.json"), "utf8"));
for (const [file, expected] of Object.entries(manifest.sources)) {
  const bytes = await readFile(resolve(root, file));
  if (createHash("sha256").update(bytes).digest("hex") !== expected) throw new Error(`Web brand source changed: ${file}. Regenerate the web exports.`);
}
const routes = manifest.assets.map(asset => [asset.route, "public/branding/" + basename(asset.source), asset.contentType]);
const expectedRoutes = "// Generated by scripts/generate-web-brand-assets.py.\nexport const FAVICON_STYLE_HASH = " + JSON.stringify(manifest.faviconStyleHash) + ";\nexport const FAVICON_STYLE_ROUTES = " + JSON.stringify(manifest.faviconStyleRoutes) + " as const;\nexport const BRAND_WEB_ASSETS = " + JSON.stringify(routes, null, 2) + " as const;\n";
if (await readFile(resolve(root, "src/brand-web-assets.ts"), "utf8") !== expectedRoutes) throw new Error("Web brand routes differ from the generated asset manifest.");
for (const asset of manifest.assets) {
  const bytes = await readFile(resolve(root, asset.source));
  if (createHash("sha256").update(bytes).digest("hex") !== asset.sha256) throw new Error(`Web brand export changed: ${asset.source}`);
  await writeFile(resolve(output, basename(asset.source)), bytes);
}
console.log("Copied exact canonical lockups and verified web brand resources.");
